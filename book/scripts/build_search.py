"""Rebuild the static search index after editing chapter HTML (Python stdlib only)."""
import json
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAGS = {"h1", "h2", "h3", "h4", "p", "li", "td", "th", "summary", "pre", "dt", "dd"}


class IndexParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.article = False
        self.blocks = []
        self.active = []
        self.section = "Introduction"
        self.ignored = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "article":
            self.article = True
        if not self.article:
            return
        if tag in {"script", "style", "svg"}:
            self.ignored += 1
        if tag in TAGS and not self.ignored:
            block = {"tag": tag, "text": "", "section": self.section}
            self.blocks.append(block)
            self.active.append(block)

    def handle_data(self, data):
        if not self.ignored:
            for block in self.active:
                block["text"] += data

    def handle_endtag(self, tag):
        if tag in {"script", "style", "svg"} and self.ignored:
            self.ignored -= 1
        if self.active and self.active[-1]["tag"] == tag:
            block = self.active.pop()
            if tag == "h2":
                self.section = " ".join(block["text"].split())
                block["section"] = self.section
        if tag == "article":
            self.article = False


entries = []
for path in sorted(ROOT.glob("*.html")):
    parser = IndexParser()
    parser.feed(path.read_text())
    title = next(b["text"] for b in parser.blocks if b["tag"] == "h1")
    for i, block in enumerate(parser.blocks):
        text = " ".join(block["text"].split())
        if text:
            entries.append(dict(file=path.name, title=" ".join(title.split()),
                                section=block["section"], id=f"search-{i}", text=text))
(ROOT / "assets/search-index.js").write_text(
    "// Generated by book/scripts/build_search.py\nwindow.MI_SEARCH_INDEX = "
    + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"Indexed {len(entries)} passages across 13 pages.")
